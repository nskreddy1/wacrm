// Dumps the live public-schema structure (tables, columns, indexes,
// foreign keys, RLS policies, functions, triggers) as markdown so the
// agent context pack can document the real database, not the
// migration history. Read-only: runs only SELECTs against catalogs.
import process from 'node:process';
import pg from 'pg';

const { Client } = pg;
const connectionString =
  process.env.SUPABASE_DB_URL ??
  process.env.POSTGRES_URL ??
  process.env.DATABASE_URL;

if (!connectionString) {
  console.error('Missing SUPABASE_DB_URL / POSTGRES_URL / DATABASE_URL');
  process.exit(1);
}

const url = new URL(connectionString);
url.searchParams.delete('sslmode');
const client = new Client({
  connectionString: url.toString(),
  ssl: { rejectUnauthorized: false },
});

const out = [];
const say = (line = '') => out.push(line);

try {
  await client.connect();

  const { rows: tables } = await client.query(`
    SELECT c.relname AS table_name,
           c.relrowsecurity AS rls_enabled,
           COALESCE(obj_description(c.oid), '') AS comment,
           (SELECT reltuples::bigint FROM pg_class WHERE oid = c.oid) AS approx_rows
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
    ORDER BY c.relname
  `);

  const { rows: columns } = await client.query(`
    SELECT table_name, column_name, data_type, udt_name,
           is_nullable, column_default, character_maximum_length,
           ordinal_position
    FROM information_schema.columns
    WHERE table_schema = 'public'
    ORDER BY table_name, ordinal_position
  `);

  const { rows: indexes } = await client.query(`
    SELECT tablename AS table_name, indexname, indexdef
    FROM pg_indexes
    WHERE schemaname = 'public'
    ORDER BY tablename, indexname
  `);

  const { rows: fks } = await client.query(`
    SELECT tc.table_name, kcu.column_name, tc.constraint_name,
           ccu.table_name AS foreign_table, ccu.column_name AS foreign_column,
           rc.delete_rule
    FROM information_schema.table_constraints tc
    JOIN information_schema.key_column_usage kcu
      ON kcu.constraint_name = tc.constraint_name
     AND kcu.table_schema = tc.table_schema
    JOIN information_schema.constraint_column_usage ccu
      ON ccu.constraint_name = tc.constraint_name
     AND ccu.table_schema = tc.table_schema
    JOIN information_schema.referential_constraints rc
      ON rc.constraint_name = tc.constraint_name
     AND rc.constraint_schema = tc.table_schema
    WHERE tc.table_schema = 'public' AND tc.constraint_type = 'FOREIGN KEY'
    ORDER BY tc.table_name, kcu.column_name
  `);

  const { rows: checks } = await client.query(`
    SELECT rel.relname AS table_name, con.conname,
           pg_get_constraintdef(con.oid) AS definition
    FROM pg_constraint con
    JOIN pg_class rel ON rel.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = rel.relnamespace
    WHERE n.nspname = 'public' AND con.contype = 'c'
    ORDER BY rel.relname, con.conname
  `);

  const { rows: policies } = await client.query(`
    SELECT tablename AS table_name, policyname, cmd, roles,
           COALESCE(qual, '') AS using_expr,
           COALESCE(with_check, '') AS check_expr
    FROM pg_policies
    WHERE schemaname = 'public'
    ORDER BY tablename, policyname
  `);

  const { rows: functions } = await client.query(`
    SELECT p.proname AS name,
           pg_get_function_identity_arguments(p.oid) AS args,
           pg_get_function_result(p.oid) AS returns,
           p.prosecdef AS security_definer
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
    ORDER BY p.proname
  `);

  const { rows: triggers } = await client.query(`
    SELECT event_object_table AS table_name, trigger_name,
           action_timing, event_manipulation, action_statement
    FROM information_schema.triggers
    WHERE trigger_schema = 'public'
    ORDER BY event_object_table, trigger_name
  `);

  const { rows: enums } = await client.query(`
    SELECT t.typname AS name,
           string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder) AS values
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    GROUP BY t.typname
    ORDER BY t.typname
  `);

  const byTable = (rows, name) => rows.filter((r) => r.table_name === name);

  say(`# Live database structure`);
  say();
  say(`Generated by \`scripts/dump-schema-doc.mjs\` against the live`);
  say(`Supabase Postgres. ${tables.length} tables in \`public\`.`);
  say();

  if (enums.length) {
    say(`## Enum types`);
    say();
    for (const e of enums) say(`- \`${e.name}\`: ${e.values}`);
    say();
  }

  say(`## Tables`);
  say();
  for (const t of tables) {
    say(`### ${t.table_name}`);
    say();
    say(`RLS: ${t.rls_enabled ? 'enabled' : 'DISABLED'} · approx rows: ${t.approx_rows}`);
    if (t.comment) say(`\n${t.comment}`);
    say();
    say(`| Column | Type | Null | Default |`);
    say(`| --- | --- | --- | --- |`);
    for (const c of byTable(columns, t.table_name)) {
      const type =
        c.data_type === 'character varying' && c.character_maximum_length
          ? `varchar(${c.character_maximum_length})`
          : c.data_type === 'USER-DEFINED'
            ? c.udt_name
            : c.data_type === 'ARRAY'
              ? `${c.udt_name.replace(/^_/, '')}[]`
              : c.data_type;
      const def = c.column_default ? `\`${c.column_default}\`` : '—';
      say(
        `| ${c.column_name} | ${type} | ${c.is_nullable === 'YES' ? 'yes' : 'no'} | ${def} |`
      );
    }
    say();

    const tFks = byTable(fks, t.table_name);
    if (tFks.length) {
      say(`Foreign keys:`);
      for (const f of tFks)
        say(
          `- \`${f.column_name}\` → \`${f.foreign_table}.${f.foreign_column}\` (on delete ${f.delete_rule.toLowerCase()})`
        );
      say();
    }

    const tIdx = byTable(indexes, t.table_name);
    if (tIdx.length) {
      say(`Indexes:`);
      for (const i of tIdx) say(`- \`${i.indexname}\`: ${i.indexdef}`);
      say();
    }

    const tChecks = byTable(checks, t.table_name);
    if (tChecks.length) {
      say(`Check constraints:`);
      for (const c of tChecks) say(`- \`${c.conname}\`: ${c.definition}`);
      say();
    }

    const tPol = byTable(policies, t.table_name);
    if (tPol.length) {
      say(`RLS policies:`);
      for (const p of tPol) {
        say(`- \`${p.policyname}\` (${p.cmd}, roles ${p.roles})`);
        if (p.using_expr) say(`  - USING: ${p.using_expr}`);
        if (p.check_expr) say(`  - WITH CHECK: ${p.check_expr}`);
      }
      say();
    }

    const tTrig = byTable(triggers, t.table_name);
    if (tTrig.length) {
      say(`Triggers:`);
      for (const g of tTrig)
        say(
          `- \`${g.trigger_name}\`: ${g.action_timing} ${g.event_manipulation} → ${g.action_statement}`
        );
      say();
    }
  }

  say(`## Functions`);
  say();
  for (const f of functions)
    say(
      `- \`${f.name}(${f.args})\` → ${f.returns}${f.security_definer ? ' **SECURITY DEFINER**' : ''}`
    );
  say();

  console.log(out.join('\n'));
} catch (error) {
  console.error(error);
  process.exitCode = 1;
} finally {
  await client.end().catch(() => undefined);
}
